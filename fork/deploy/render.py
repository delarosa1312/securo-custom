#!/usr/bin/env python3
"""Render the single compose files Coolify takes (one file per resource) from upstream's docker-compose.prod.yml
and our overrides, without interpolating variables, so Coolify still manages every ${VAR}.

  fork/deploy/coolify/production.yml = docker-compose.prod.yml + production.override.yml
  fork/deploy/coolify/staging.yml    = the same + staging.override.yml

Anchors and merge keys are expanded (Coolify does not document them), `x-` fields are dropped, the MCP server
loses its `agents` profile (Coolify starts no profiles, and production runs MCP), and the plugin services
(profile `plugins`) are left out (see docs/fork/DEPLOY.md to add them).

Usage: render.py [--check]   --check fails when a rendered file is stale (after an upstream sync or an edit).
Needs `docker compose` and PyYAML.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DEPLOY = ROOT / "fork" / "deploy"
OUTPUTS = {
    "production": ["production.override.yml"],
    "staging": ["production.override.yml", "staging.override.yml"],
}
HEADER = """\
# GENERATED by fork/deploy/render.py from docker-compose.prod.yml and fork/deploy/{sources}. Do not edit:
# change those and run fork/deploy/render.py. For Coolify ({name}): see docs/fork/DEPLOY.md.
"""


def render(name: str, overrides: list[str]) -> str:
    files = ["-f", str(ROOT / "docker-compose.prod.yml")]
    for override in overrides:
        files += ["-f", str(DEPLOY / override)]
    raw = subprocess.check_output(
        [
            "docker",
            "compose",
            "-p",
            "securo",
            "--project-directory",
            str(ROOT),
            *files,
            "--profile",
            "agents",
            "config",
            "--no-interpolate",
            "--no-path-resolution",
            "--no-normalize",
        ],
        env={
            k: os.environ[k]
            for k in ("PATH", "HOME", "DOCKER_HOST", "DOCKER_CONTEXT")
            if k in os.environ
        },
        text=True,
    )
    doc = yaml.safe_load(raw)
    doc = {key: value for key, value in doc.items() if not key.startswith("x-")}
    services = doc["services"]
    for service in [s for s, spec in services.items() if "plugins" in (spec.get("profiles") or [])]:
        del services[service]
    services["mcp-server"].pop("profiles", None)
    if not any("plugins" in (spec.get("networks") or {}) for spec in services.values()):
        doc.get("networks", {}).pop("plugins", None)
    doc.get("volumes", {}).pop("plugins", None)
    body = yaml.safe_dump(doc, sort_keys=False, width=200, default_flow_style=False)
    return HEADER.format(sources=", ".join(overrides), name=name) + body


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, overrides in OUTPUTS.items():
        target = DEPLOY / "coolify" / f"{name}.yml"
        text = render(name, overrides)
        if check:
            if not target.exists() or target.read_text() != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(exist_ok=True)
            target.write_text(text)
            print(f"wrote {target.relative_to(ROOT)}")
    if stale:
        print("stale, run fork/deploy/render.py: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
